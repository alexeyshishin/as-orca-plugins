import { build } from "esbuild"
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const buildRoot = path.dirname(fileURLToPath(import.meta.url))
const pluginRoot = path.dirname(buildRoot)
const editorHtmlPath = path.join(pluginRoot, "editor", "index.html")
const noticesPath = path.join(pluginRoot, "THIRD_PARTY_NOTICES.txt")
const cssPath = path.join(buildRoot, "src", "editor.css")
const entryPath = path.join(buildRoot, "src", "main.js")

const FORBIDDEN_IN_SCRIPT = [
  { pattern: /\beval\s*\(/, label: "eval(" },
  { pattern: /\bnew\s+Function\b/, label: "new Function" },
  { pattern: /(?<![.\w$])Function\s*\(/, label: "Function(" },
  { pattern: /<\/script/i, label: "</script" },
  { pattern: /<script/i, label: "<script" }
]
const FORBIDDEN_IN_STYLE = [
  { pattern: /<\/style/i, label: "</style" },
  { pattern: /@import/i, label: "@import" },
  { pattern: /url\s*\(/i, label: "url(" }
]
const LICENSE_FILE_NAMES = ["LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "LICENCE.md", "LICENSE-MIT"]

function findViolations(source, rules) {
  return rules.filter((rule) => rule.pattern.test(source)).map((rule) => rule.label)
}

function packageDirectory(inputPath) {
  const marker = "node_modules/"
  const index = inputPath.lastIndexOf(marker)
  if (index === -1) return null
  const segments = inputPath.slice(index + marker.length).split("/")
  const length = segments[0].startsWith("@") ? 2 : 1
  return inputPath.slice(0, index + marker.length) + segments.slice(0, length).join("/")
}

function readLicenseText(directory) {
  for (const name of LICENSE_FILE_NAMES) {
    const file = path.join(buildRoot, directory, name)
    if (existsSync(file)) return readFileSync(file, "utf8").trim()
  }
  throw new Error(`no license file in ${directory}`)
}

function buildNotices(inputPaths) {
  const directories = [...new Set(inputPaths.map(packageDirectory).filter(Boolean))]
  const packages = directories.map((directory) => {
    const manifest = JSON.parse(readFileSync(path.join(buildRoot, directory, "package.json"), "utf8"))
    return { name: manifest.name, version: manifest.version, license: manifest.license, text: readLicenseText(directory) }
  })
  packages.sort((left, right) => left.name.localeCompare(right.name, "en"))
  const sections = packages.map(
    (item) => `${item.name} ${item.version} (${item.license})\n${"-".repeat(40)}\n${item.text}\n`
  )
  return `Third-party notices for Live Markdown.\nGenerated by build/build.mjs from the packages bundled into editor/index.html. Do not edit.\n\n${sections.join("\n")}`
}

function composeHtml(script, style) {
  return [
    "<!doctype html>",
    '<html lang="en">',
    "<head>",
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    "<title>Live Markdown</title>",
    "<style>",
    style.trim(),
    "</style>",
    "</head>",
    "<body>",
    '<div id="editor"></div>',
    "<script>",
    script.trim(),
    "</script>",
    "</body>",
    "</html>",
    ""
  ].join("\n")
}

async function main() {
  const result = await build({
    absWorkingDir: buildRoot,
    entryPoints: [entryPath],
    bundle: true,
    format: "iife",
    platform: "browser",
    target: "es2022",
    write: false,
    metafile: true,
    legalComments: "inline",
    minify: false,
    sourcemap: false,
    logLevel: "silent",
    outfile: "bundle.js"
  })
  for (const warning of result.warnings) console.warn(warning.text)
  const script = result.outputFiles[0].text
  const style = readFileSync(cssPath, "utf8")
  const problems = [
    ...findViolations(script, FORBIDDEN_IN_SCRIPT).map((label) => `script contains ${label}`),
    ...findViolations(style, FORBIDDEN_IN_STYLE).map((label) => `style contains ${label}`)
  ]
  if (problems.length > 0) throw new Error(problems.join("; "))
  const html = composeHtml(script, style)
  mkdirSync(path.dirname(editorHtmlPath), { recursive: true })
  writeFileSync(editorHtmlPath, html)
  writeFileSync(noticesPath, buildNotices(Object.keys(result.metafile.inputs)))
  console.log(`editor/index.html ${Buffer.byteLength(html)} bytes`)
}

main().catch((error) => {
  console.error(`build failed: ${error.message}`)
  process.exitCode = 1
})
